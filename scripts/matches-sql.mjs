// Emit SQL that syncs data/ucl2027.json into the Supabase `matches` table and
// proposes ballot rows for any phase not seeded yet.
//
//   node scripts/matches-sql.mjs > supabase/matches.sql
//
// Paste the output into the Supabase SQL editor (or run `supabase db query`).
// Safe to re-run: matches are upserted by num; ballots are inserted only when
// the phase does not exist yet (adjust opens_at / locks_at by hand if needed).
//
// Ballot defaults: opens now, locks at the first kickoff of the phase. For the
// league phase the lock is Matchday 2's first kickoff, because Matchday 1 was
// played before the game went live (see SETUP.md).

import { readFileSync } from 'node:fs';

const data = JSON.parse(readFileSync(new URL('../data/ucl2027.json', import.meta.url), 'utf8'));

const LABEL = {
  league: 'League phase', playoff: 'Knockout play-off', r16: 'Round of 16',
  qf: 'Quarter-finals', sf: 'Semi-finals', final: 'Final',
};

function kickoffIso(m) {
  const [, hh, mm, off] = m.time.match(/^(\d{2}):(\d{2}) UTC([+-]\d+)$/);
  const sign = off.startsWith('-') ? '-' : '+';
  const pad = String(Math.abs(parseInt(off, 10))).padStart(2, '0');
  return `${m.date}T${hh}:${mm}:00${sign}${pad}:00`;
}
const q = s => `'${String(s).replace(/'/g, "''")}'`;

const phases = [...new Set(data.matches.map(m => m.phase))];
let sql = `-- generated by scripts/matches-sql.mjs on ${new Date().toISOString()}\n`;
sql += `-- ${data.matches.length} matches, phases: ${phases.join(', ')}\n\n`;

const PLACEHOLDER = /^(tbd|tba|winner|loser|runner|1st|2nd|w\d+|l\d+)\b/i;
const drawn = m => !PLACEHOLDER.test(m.team1) && !PLACEHOLDER.test(m.team2);
const emitted = new Set(); // phases whose ballot row exists -> their matches may be inserted (FK)

// Ballots first (matches reference them).
for (const phase of phases) {
  const ms = data.matches.filter(m => m.phase === phase).sort((a, b) => Date.parse(kickoffIso(a)) - Date.parse(kickoffIso(b)));
  let lock;
  if (phase === 'league') {
    const md2 = ms.find(m => m.round === 'Matchday 2') ?? ms[0];
    lock = kickoffIso(md2);
  } else {
    lock = kickoffIso(ms[0]);
  }
  const undrawn = ms.filter(m => !drawn(m)).length;
  if (undrawn) {
    // ESPN lists knockout rounds with "TBD Home / TBD Away" long before the
    // draw. A ballot must not open until every pairing is known.
    sql += `-- ${phase}: ${undrawn}/${ms.length} matches still undrawn (TBD) - ballot and its matches NOT emitted; re-run after the draw.\n`;
    process.stderr.write(`note: ${phase} ballot + matches skipped, ${undrawn} undrawn matches\n`);
    continue;
  }
  emitted.add(phase);
  const label = q(LABEL[phase] ?? phase);
  sql += `insert into public.ballots (phase, label, opens_at, locks_at)\n`;
  // opens_at stays before locks_at even when pasted late (check constraint).
  sql += `  values (${q(phase)}, ${label}, least(now(), ${q(lock)}::timestamptz - interval '1 minute'), ${q(lock)})\n`;
  if (phase === 'league') {
    sql += `  on conflict (phase) do nothing;\n`;
  } else {
    // Knockout kickoffs firm up after the draw: move the lock along with the
    // earliest kickoff as long as the ballot has not locked yet.
    sql += `  on conflict (phase) do update set locks_at = excluded.locks_at\n`;
    sql += `    where public.ballots.locks_at > now() and public.ballots.locks_at <> excluded.locks_at;\n`;
  }
}
sql += '\n';
sql += `-- Matches (upsert by num). Kickoffs move with ESPN; picks stay keyed by num.\n`;

const rows = data.matches.filter(m => emitted.has(m.phase));
if (!rows.length) { process.stdout.write(sql + '-- nothing to insert\n'); process.exit(0); }
sql += `insert into public.matches (num, espn, phase, round, kickoff, team1, team2) values\n`;
sql += rows.map(m =>
  `  (${m.num}, ${q(m.espn)}, ${q(m.phase)}, ${q(m.round + (m.leg ? ` (leg ${m.leg})` : ''))}, ${q(kickoffIso(m))}, ${q(m.team1)}, ${q(m.team2)})`,
).join(',\n');
sql += `\non conflict (num) do update set\n  espn = excluded.espn, phase = excluded.phase, round = excluded.round,\n  kickoff = excluded.kickoff, team1 = excluded.team1, team2 = excluded.team2;\n`;

process.stdout.write(sql);
